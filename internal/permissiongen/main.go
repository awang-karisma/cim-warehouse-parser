// Command permissiongen emits the frontend type for the server capability catalog.
package main

import (
	"flag"
	"fmt"
	"log"
	"os"
	"slices"
	"strings"

	"github.com/awang-karisma/warehouse-parser/pkg/model"
)

func main() {
	out := flag.String("out", "", "output TypeScript path")
	flag.Parse()
	if *out == "" {
		log.Fatal("-out is required")
	}
	var b strings.Builder
	b.WriteString("// Code generated by go generate ./pkg/model; DO NOT EDIT.\n\nexport type Permission =\n")
	permissions := slices.Sorted(model.Permissions)
	for i, permission := range permissions {
		if i > 0 && permission == permissions[i-1] {
			log.Fatalf("duplicate permission %q", permission)
		}
		fmt.Fprintf(&b, "  | %q", permission)
		if i == len(permissions)-1 {
			b.WriteString(";")
		}
		b.WriteByte('\n')
	}
	if err := os.WriteFile(*out, []byte(b.String()), 0o644); err != nil {
		log.Fatal(err)
	}
}
